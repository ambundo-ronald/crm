const { chromium, expect } = require('@playwright/test')
const fs = require('node:fs/promises')
;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const context = await browser.newContext({ baseURL: 'http://127.0.0.1:18000', viewport: { width: 1440, height: 960 } })
    await context.addInitScript(() => localStorage.setItem('crm_persona_captured', '1'))
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    const login = await context.request.post('/api/method/login', { form: { usr: 'Administrator', pwd: 'Local-Dev2-Only-2026' } })
    expect(login.status()).toBe(200)
    await page.goto('/crm/appointments')
    await expect(page.locator('.month-cell')).toHaveCount(42)
    const onboarding = page.locator('div.fixed.z-50.right-0.w-80')
    if (await onboarding.isVisible()) await onboarding.locator(':scope > div').first().getByRole('button').last().click()

    await page.getByLabel('Go to date', { exact: true }).fill('2035-06-22')
    await page.getByLabel('Go to date', { exact: true }).blur()
    const subject = 'Calendar design review ' + Date.now()
    await page.getByRole('button', { name: 'Book appointment on 2035-06-22', exact: true }).first().click()
    await expect(page.getByLabel('Starts', { exact: true })).toHaveValue('2035-06-22T09:00')
    await page.getByLabel('Appointment title', { exact: true }).fill(subject)
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await page.getByLabel('Search appointments', { exact: true }).fill(subject)
    await expect(page.locator('.month-event').filter({ hasText: subject })).toBeVisible()
    await page.locator('.month-event').filter({ hasText: subject }).click()
    await expect(page.getByRole('dialog', { name: 'Appointment details' })).toContainText('No lead yet')
    await page.getByRole('button', { name: 'Close details', exact: true }).click()
    await page.getByLabel('Open', { exact: true }).uncheck()
    await expect(page.locator('.month-event').filter({ hasText: subject })).toHaveCount(0)
    await page.getByLabel('Open', { exact: true }).check()
    await page.getByLabel('Search appointments', { exact: true }).fill('no-match-unique')
    await expect(page.locator('.month-event')).toHaveCount(0)
    await page.getByLabel('Search appointments', { exact: true }).fill('')
    await page.getByLabel('View', { exact: true }).selectOption('Week')
    await expect(page.locator('.time-day')).toHaveCount(7)
    await expect(page.locator('.time-event').filter({ hasText: subject })).toBeVisible()
    await page.getByLabel('View', { exact: true }).selectOption('Day')
    await expect(page.locator('.time-day')).toHaveCount(1)
    await page.getByRole('button', { name: 'Book appointment', exact: true }).click()
    await page.getByLabel('Starts', { exact: true }).fill('2035-06-22T09:00')
    await page.getByLabel('Ends', { exact: true }).fill('2035-06-22T09:30')
    await page.getByLabel('Appointment title', { exact: true }).fill(subject + ' overlap')
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    const blocks = page.locator('.time-event').filter({ hasText: subject })
    await expect(blocks).toHaveCount(2)
    const boxes = await blocks.evaluateAll(elements => elements.map(el => ({ left: el.getBoundingClientRect().left, width: el.getBoundingClientRect().width })))
    expect(boxes[0].left).not.toBe(boxes[1].left)
    await fs.mkdir('test-results', { recursive: true })
    await page.screenshot({ path: 'test-results/calendar-day.png', fullPage: true })
    await page.getByLabel('View', { exact: true }).selectOption('Month')
    await expect(page.locator('.calendar-content')).toHaveAttribute('aria-busy', 'false')
    await page.screenshot({ path: 'test-results/calendar-month.png', fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.reload()
    await expect(page.locator('.calendar-content')).toHaveAttribute('aria-busy', 'false')
    await expect(page.locator('.month-cell')).toHaveCount(42)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: 'test-results/calendar-mobile.png', fullPage: true })
    expect(errors).toEqual([])
    console.log('PASS: month/week/day, click-to-book, event details, search, overlap layout and mobile width')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
