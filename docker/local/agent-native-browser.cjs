const { chromium, expect } = require('@playwright/test')

;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const baseURL = 'http://127.0.0.1:18000'
  const stamp = Date.now()
  try {
    const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
    await context.addInitScript(() => localStorage.setItem('crm_persona_captured', '1'))
    expect((await context.request.post('/api/method/login', { form: { usr: 'dev2.agent.a@example.invalid', pwd: 'Local-Dev2-Only-2026' } })).status()).toBe(200)
    const page = await context.newPage(), errors = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('response', async r => { if (r.status() >= 400 && r.url().includes('/api/')) console.log('UI API failure', r.status(), r.url(), r.request().postData(), (await r.text().catch(() => '')).slice(0,1000)) })
    page.on('console', m => { if (m.type() === 'error' && !m.text().startsWith('Failed to load resource:')) errors.push(m.text()) })
    await page.goto('/crm-agent')
    await expect(page).toHaveURL(/\/crm\/leads\/view\/list/)
    await expect(page.getByRole('button', { name: 'Create', exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: 'Deals', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: 'Create', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.locator('[data-name="first_name"] input').fill(`Native agent lead ${stamp}`)
    await dialog.getByRole('button', { name: 'Create', exact: true }).click()
    await expect(dialog).toHaveCount(0, { timeout: 10000 })
    await expect(page).toHaveURL(/\/crm\/leads\/CRM-LEAD-/)
    const lead = new URL(page.url()).pathname.split('/').pop()
    await expect(page.getByRole('button', { name: 'Convert to Deal', exact: true })).toHaveCount(0)
    await page.getByRole('tab', { name: 'Tasks', exact: true }).click()
    await page.getByRole('button', { name: 'New Task', exact: true }).click()
    await dialog.locator('[data-name="title"] input').fill(`Native follow-up ${stamp}`)
    await dialog.getByRole('button', { name: 'Create', exact: true }).click()
    await expect(dialog).toHaveCount(0, { timeout: 10000 })
    await expect(page.getByText(`Native follow-up ${stamp}`, { exact: true })).toBeVisible()
    await page.goto('/crm/contacts')
    await page.getByRole('button', { name: 'Create', exact: true }).click()
    await dialog.locator('[data-name="first_name"] input').fill(`Native contact ${stamp}`)
    await dialog.locator('[data-name="email_id"] input').fill(`native.${stamp}@example.invalid`)
    await dialog.getByRole('button', { name: 'Create', exact: true }).click()
    await expect(dialog).toHaveCount(0, { timeout: 10000 })
    await expect(page).toHaveURL(/\/crm\/contacts\//)
    await expect(page.getByRole('tab', { name: 'Deals' })).toHaveCount(0)

    const csrf = await page.evaluate(() => window.csrf_token)
    const headers = { 'X-Frappe-CSRF-Token': csrf }
    const list = await context.request.post('/api/method/crm.api.doc.get_data', { headers, data: { doctype: 'CRM Lead', filters: { owner: 'dev2.agent.b@example.invalid' } } })
    expect(list.status()).toBe(200)
    expect((await list.json()).message.total_count).toBe(0)
    for (const path of ['/api/resource/Customer', '/api/v2/document/CRM Lead', '/private/files/unknown.pdf', '/api/method/crm.api.erpnext_sync.preview', '/api/method/frappe.realtime.get_user_info']) {
      expect((await context.request.get(path)).status()).toBe(403)
    }
    const forbidden = await context.request.post('/api/method/frappe.client.get', { headers, data: { doctype: 'User', name: 'Administrator' } })
    expect(forbidden.status()).toBe(403)
    const forged = await context.request.post('/api/method/frappe.client.set_value', { headers, data: { doctype: 'CRM Lead', name: lead, fieldname: 'owner', value: 'dev2.agent.b@example.invalid' } })
    expect(forged.status()).toBe(403)
    for (const path of ['/crm/my-day', '/crm/appointments', '/crm/tasks']) {
      await page.goto(path)
      await expect(page.locator('body')).not.toContainText('Not permitted')
    }
    await page.goto('/crm/deals')
    await expect(page).toHaveURL(/\/crm\/leads\/view\/list/)
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(`/crm/leads/${lead}`)
    await expect(page.getByRole('tab', { name: 'Details', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Convert', exact: true })).toHaveCount(0)
    await page.screenshot({ path: 'test-results/agent-native-mobile.png', fullPage: true })
    expect(errors).toEqual([])

    const staff = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
    await staff.addInitScript(() => localStorage.setItem('crm_persona_captured', '1'))
    expect((await staff.request.post('/api/method/login', { form: { usr: 'Administrator', pwd: 'Local-Dev2-Only-2026' } })).status()).toBe(200)
    const staffPage = await staff.newPage()
    await staffPage.goto('/crm/leads')
    await expect(staffPage.getByRole('button', { name: 'Create', exact: true })).toBeVisible()
    await staffPage.locator('button').filter({ has: staffPage.locator('.lucide-chevron-down') }).first().click()
    await staffPage.getByText('Settings', { exact: true }).click()
    await staffPage.locator('[data-page="Invite User"]').click()
    await staffPage.getByRole('combobox').click()
    await expect(staffPage.getByRole('option', { name: 'Agent', exact: true })).toHaveCount(1)
    await staffPage.getByRole('option', { name: 'Agent', exact: true }).click()
    await staffPage.locator('[data-page="Agents"]').click()
    await expect(staffPage.getByRole('button', { name: 'Invite an Agent', exact: true })).toBeVisible()
    await expect(staffPage.getByRole('button', { name: 'Create agent', exact: true })).toHaveCount(0)
    console.log('PASS: native agent lead/contact creation, follow-up creation, calendar/My Day/tasks, mobile lead, HTTP isolation, legacy redirect and administrator invitation UI. No email sent.')
  } finally {
    await browser.close()
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
