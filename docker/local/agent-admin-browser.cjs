const { chromium, expect } = require('@playwright/test')
const { execFileSync } = require('node:child_process')
const fs = require('node:fs/promises')
;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const baseURL = 'http://127.0.0.1:18000'
  const stamp = Date.now(), email = `dev2.admin-browser.${stamp}@example.invalid`
  const path = '/api/method/crm.api.agent_admin.'
  const agentPath = '/api/method/crm.api.agent.'
  const password = 'Local-Dev2-Only-2026'
  try {
    const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
    await context.addInitScript(() => localStorage.setItem('crm_persona_captured', '1'))
    expect((await context.request.post('/api/method/login', { form: { usr: 'Administrator', pwd: password } })).status()).toBe(200)
    const page = await context.newPage(), errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.goto('/crm/leads')
    await page.getByRole('button', { name: /CRM.*Administrator/ }).click()
    await page.getByText('Settings', { exact: true }).click()
    await page.locator('[data-page="Agents"]').click()
    await expect(page.getByRole('heading', { name: 'Agents', exact: true })).toBeVisible()
    await page.getByLabel('First name', { exact: true }).fill('Browser Agent')
    await page.getByLabel('Agent email', { exact: true }).fill(email)
    await page.getByRole('button', { name: 'Create agent', exact: true }).click()
    const card = page.locator(`[data-agent="${email}"]`)
    await expect(card).toBeVisible()
    await expect(card.getByRole('button', { name: 'Send setup email', exact: true })).toBeDisabled()
    execFileSync('docker', ['cp', 'docker/local/seed-agent-admin.py', 'crm-dev2-backend-1:/workspace/frappe-bench/apps/crm/crm/_dev2_admin_fixture.py'])
    execFileSync('docker', ['exec', '-w', '/workspace/frappe-bench', 'crm-dev2-backend-1', 'bench', '--site', 'crm.localhost', 'execute', 'crm._dev2_admin_fixture.run', '--kwargs', JSON.stringify({ email })], { stdio: 'pipe' })
    const agent = await browser.newContext({ baseURL })
    expect((await agent.request.post('/api/method/login', { form: { usr: email, pwd: password } })).status()).toBe(200)
    const agentPage = await agent.newPage()
    await agentPage.goto('/crm-agent')
    const csrf = await agentPage.locator('meta[name="csrf-token"]').getAttribute('content')
    const saved = await agent.request.post(agentPath + 'save_lead', { data: { data: { first_name: 'Retained administration browser lead' } }, headers: { 'X-Frappe-CSRF-Token': csrf } })
    expect(saved.status()).toBe(200)
    const lead = (await saved.json()).message.name
    const token = await browser.newContext({ baseURL, extraHTTPHeaders: { Authorization: `token local-admin-browser-${stamp}:Local-Dev2-Browser-Token-Only-2026` } })
    expect((await token.request.get(agentPath + 'list_leads')).status()).toBe(200)
    expect((await agent.request.get(path + 'list_agents')).status()).toBe(403)
    await page.getByRole('button', { name: 'Refresh', exact: true }).click()
    await card.getByRole('button', { name: 'Suspend access', exact: true }).click()
    await card.getByLabel('Reason', { exact: true }).fill('Browser suspension review')
    await card.getByRole('button', { name: 'Confirm action', exact: true }).click()
    await expect(card.getByRole('button', { name: 'Reactivate access', exact: true })).toBeVisible()
    for (const client of [agent, token]) expect((await client.request.get(agentPath + 'list_leads')).status()).toBeGreaterThanOrEqual(400)
    const fresh = await browser.newContext({ baseURL })
    expect((await fresh.request.post('/api/method/login', { form: { usr: email, pwd: password } })).status()).toBeGreaterThanOrEqual(400)
    expect((await context.request.get(path + 'list_agents')).status()).toBe(200)
    await card.getByRole('button', { name: 'Reactivate access', exact: true }).click()
    await card.getByLabel('Reason', { exact: true }).fill('Browser reactivation review')
    await card.getByRole('button', { name: 'Confirm action', exact: true }).click()
    await expect(card.getByRole('button', { name: 'Suspend access', exact: true })).toBeVisible()
    for (const client of [agent, token]) expect((await client.request.get(agentPath + 'list_leads')).status()).toBeGreaterThanOrEqual(400)
    expect((await fresh.request.post('/api/method/login', { form: { usr: email, pwd: password } })).status()).toBe(200)
    const leads = (await (await fresh.request.get(agentPath + 'list_leads')).json()).message
    expect(leads.map(row => row.name)).toContain(lead)
    expect(leads.every(row => row.first_name === 'Retained administration browser lead')).toBe(true)
    await card.getByRole('button', { name: 'Access history', exact: true }).click()
    await expect(card).toContainText('Browser suspension review')
    await expect(card).toContainText('Browser reactivation review')
    await expect(card).toContainText('Administrator')
    await fs.mkdir('test-results', { recursive: true })
    await page.screenshot({ path: 'test-results/agent-administration.png', fullPage: true })
    const staff = await browser.newContext({ baseURL })
    expect((await staff.request.post('/api/method/login', { form: { usr: 'dev2.sales.a@example.invalid', pwd: password } })).status()).toBe(200)
    expect((await staff.request.get(path + 'list_agents')).status()).toBe(403)
    const staffPage = await staff.newPage()
    await staffPage.goto('/crm/leads')
    await staffPage.locator('button').filter({ has: staffPage.locator('.lucide-chevron-down') }).first().click()
    await staffPage.getByText('Settings', { exact: true }).click()
    await expect(staffPage.locator('[data-page="Agents"]')).toHaveCount(0)
    expect(errors).toEqual([])
    await card.getByRole('button', { name: 'Suspend access', exact: true }).click()
    await card.getByLabel('Reason', { exact: true }).fill('Synthetic browser check complete')
    await card.getByRole('button', { name: 'Confirm action', exact: true }).click()
    await expect(card.getByRole('button', { name: 'Reactivate access', exact: true })).toBeVisible()
    console.log('PASS: agent creation, muted invitations, suspension/session/token revocation, reactivation with retained lead, audit history, admin session preserved and staff denial. Synthetic account suspended.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
